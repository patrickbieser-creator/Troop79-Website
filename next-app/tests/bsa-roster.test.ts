import { describe, it, expect } from 'vitest';
import {
  parseBsaRosterCsv,
  buildRosterReport,
  dueState,
  RosterCsvError,
  type RosterPerson
} from '../src/lib/bsa-roster';

/**
 * BSA Roster check. The preamble and header line are verbatim from the
 * my.scouts.org "Roster Report" export (2026-10-20); member rows keep the
 * export's real shapes (multi-position adults, blank youth emails, "Never
 * Taken" YPT, blank renewal flags on New members) with made-up people.
 */
const PREAMBLE = [
  'Report: Roster Report',
  'District: Southern Shores District 06',
  'Council: Three Harbors Council 636',
  'Organization Name: Troop 0079 (F), Unity Evangelical Lutheran Church',
  'Spin Type Code: 0413',
  'Tenure: 54',
  'Report Generated By: Test Leader',
  'Date Report Generated: 10/20/2026',
  '..',
  '"This roster information is to be used only for authorized purposes on behalf of the Scouting America. Disclosing, copying, or making any inappropriate use of this roster information is strictly prohibited."'
];
const HEADER =
  '..memberid,prefix,firstname,middlename,lastname,suffix,gender,positionname,gradename,rankname,programname,age,strslsubscriber,yptstatus,stryptcompletiondate,stryptexpirationdate,streetaddress,city,statecode,zip9,primaryemail,pgprimaryemail,pgprimaryphone,primaryphone,expirydtstr,registrationstatus,cisyearlymembership,cisyearlymembershiprenewalpaid,cismanuallyended,cisunitless,cisautorenewaloptedout,renewaloptoutreasonsname';
const YOUTH_ANNA =
  '"900001","","Anna","Q","Scout","","F","Youth Member","Seventh Grade","Scout","Scouts BSA","12","Yes","Never Taken","","","","","WI","","","parent.scout@example.com","001-(414)-555-0101","","02/28/2027","New","Yes","","","No","",""';
const ADULT_ROW = (position: string) =>
  `"900002","","Robert","L","Leader","","M","${position}","","","Scouts BSA","49","No","Current","03/21/2026","03/21/2027","1 Main St","Milwaukee","WI","53221-3642","rob@example.com","","","1-414-555-0102","12/31/2026","Multiple","Yes","No","No","No","No",""`;
const YOUTH_OPTED_OUT =
  '"900003","","Carla","","Gone","","F","Youth Member","Ninth Grade","Star Scout","Scouts BSA","14","No","Never Taken","","","","","WI","","","gone.parent@example.com","(414)-555-0103","","12/31/2026","Re-Registered","Yes","No","No","No","Yes",""';

function csv(...rows: string[]) {
  return [...PREAMBLE, HEADER, ...rows].join('\r\n');
}

function person(id: number, first: string, last: string, extra: Partial<RosterPerson> = {}): RosterPerson {
  return {
    id,
    firstName: first,
    lastName: last,
    displayName: `${first} ${last}`,
    gender: null,
    phone: null,
    emails: [],
    bsaMemberId: null,
    yptCompleted: null,
    active: true,
    inactiveReason: null,
    scout: null,
    leaderRoles: [],
    ...extra
  };
}

const TODAY = '2026-10-20';

describe('parseBsaRosterCsv', () => {
  it('Parse_ReadsTheReportDate_FromThePreamble', () => {
    expect(parseBsaRosterCsv(csv(YOUTH_ANNA)).generatedOn).toBe('2026-10-20');
  });

  it('Parse_MergesAnAdultsPositions_IntoOneMember', () => {
    const roster = parseBsaRosterCsv(csv(ADULT_ROW('Key 3 Delegate'), ADULT_ROW('Assistant Scoutmaster')));
    expect(roster.members.map((m) => m.positions)).toEqual([['Key 3 Delegate', 'Assistant Scoutmaster']]);
  });

  it('Parse_ConvertsTheExpiryDate_ToIso', () => {
    expect(parseBsaRosterCsv(csv(YOUTH_ANNA)).members[0].expires).toBe('2027-02-28');
  });

  it('Parse_LeavesBlankRenewalFlags_Null', () => {
    expect(parseBsaRosterCsv(csv(YOUTH_ANNA)).members[0].autoRenewOptedOut).toBeNull();
  });

  it('Parse_ReadsTheAutoRenewOptOut', () => {
    expect(parseBsaRosterCsv(csv(YOUTH_OPTED_OUT)).members[0].autoRenewOptedOut).toBe(true);
  });

  it('Parse_ReadsYptCompletion_OnlyWhenTaken', () => {
    const roster = parseBsaRosterCsv(csv(YOUTH_ANNA, ADULT_ROW('Scoutmaster')));
    expect(roster.members.map((m) => m.yptCompleted)).toEqual([null, '2026-03-21']);
  });

  it('Parse_MarksYouthMembers', () => {
    const roster = parseBsaRosterCsv(csv(YOUTH_ANNA, ADULT_ROW('Scoutmaster')));
    expect(roster.members.map((m) => m.youth)).toEqual([true, false]);
  });

  it('Parse_TakesTheLatestExpiry_AcrossAMembersRows', () => {
    const later = ADULT_ROW('Committee Member').replace('"12/31/2026","Multiple"', '"03/31/2027","Re-Registered"');
    expect(parseBsaRosterCsv(csv(ADULT_ROW('Scoutmaster'), later)).members[0]).toMatchObject({ expires: '2027-03-31', status: 'Re-Registered' });
  });

  it('Parse_ReadsAQuotedComma_AndALeadingBom', () => {
    const quoted = ADULT_ROW('Scoutmaster').replace('"1 Main St"', '"1 Main St, Unit E"');
    expect(parseBsaRosterCsv('﻿' + csv(quoted)).members[0].email).toBe('rob@example.com');
  });

  it('Parse_RejectsAFileWithoutTheRosterHeader', () => {
    expect(() => parseBsaRosterCsv('"Posting Date","Amount"\n"1/1/2026","5"')).toThrow(RosterCsvError);
  });

  it('Parse_RejectsARosterWithNoMembers', () => {
    expect(() => parseBsaRosterCsv(csv())).toThrow(RosterCsvError);
  });
});

describe('dueState', () => {
  it('DueState_IsExpired_WhenTheDateHasPassed', () => {
    expect(dueState('2026-08-31', TODAY)).toBe('expired');
  });

  it('DueState_IsSoon_WithinSixtyDays', () => {
    expect(dueState('2026-12-19', TODAY)).toBe('soon');
  });

  it('DueState_IsOk_BeyondSixtyDays', () => {
    expect(dueState('2027-02-28', TODAY)).toBe('ok');
  });
});

describe('buildRosterReport', () => {
  const roster = () => parseBsaRosterCsv(csv(YOUTH_ANNA, ADULT_ROW('Scoutmaster'), YOUTH_OPTED_OUT));

  it('Report_MatchesByBsaId_BeforeName', () => {
    const people = [
      person(1, 'Anna', 'Scout', { bsaMemberId: '900001' }),
      person(2, 'Anna', 'Scout')
    ];
    const report = buildRosterReport(roster(), people);
    expect(report.matched.find((m) => m.memberId === '900001')).toMatchObject({ personId: 1, via: 'bsa' });
  });

  it('Report_FallsBackToName_AndSuggestsTheBsaId', () => {
    const report = buildRosterReport(roster(), [person(1, 'anna', 'SCOUT')]);
    expect(report.differences).toContainEqual(
      expect.objectContaining({ personId: 1, field: 'bsa_member_id', roster: '900001', ours: null })
    );
  });

  it('Report_NeverNameMatches_APersonWithADifferentBsaId', () => {
    const report = buildRosterReport(roster(), [person(1, 'Anna', 'Scout', { bsaMemberId: '123' })]);
    expect(report.unmatched.map((m) => m.memberId)).toContain('900001');
  });

  it('Report_ListsAMemberWithNoPerson_AsUnmatched', () => {
    const report = buildRosterReport(roster(), []);
    expect(report.unmatched.map((m) => m.memberId)).toEqual(['900001', '900002', '900003']);
  });

  it('Report_FlagsAnOlderYptDate', () => {
    const people = [person(2, 'Robert', 'Leader', { bsaMemberId: '900002', yptCompleted: '2025-03-21' })];
    const report = buildRosterReport(roster(), people);
    expect(report.differences).toContainEqual(
      expect.objectContaining({ personId: 2, field: 'ypt_completed', roster: '2026-03-21', ours: '2025-03-21' })
    );
  });

  it('Report_ComparesPhones_ByTheirDigits', () => {
    const people = [
      person(2, 'Robert', 'Leader', {
        bsaMemberId: '900002',
        yptCompleted: '2026-03-21',
        phone: '(414) 555-0102',
        emails: ['rob@example.com'],
        gender: 'M'
      })
    ];
    expect(buildRosterReport(roster(), people).differences.filter((d) => d.personId === 2)).toEqual([]);
  });

  it('Report_FlagsAnEmailWeDoNotHave', () => {
    const people = [person(2, 'Robert', 'Leader', { bsaMemberId: '900002', emails: ['other@example.com'] })];
    const report = buildRosterReport(roster(), people);
    expect(report.differences).toContainEqual(expect.objectContaining({ personId: 2, field: 'email', roster: 'rob@example.com' }));
  });

  it('Report_FlagsAMissingGender', () => {
    const people = [person(1, 'Anna', 'Scout', { bsaMemberId: '900001' })];
    const report = buildRosterReport(roster(), people);
    expect(report.differences).toContainEqual(expect.objectContaining({ personId: 1, field: 'gender', roster: 'F', ours: null }));
  });

  it('Report_ListsAnInactiveScout_WhoseRegistrationStillRuns', () => {
    const people = [
      person(3, 'Carla', 'Gone', { bsaMemberId: '900003', scout: { active: false, inactiveReason: 'dropped_out' } })
    ];
    const report = buildRosterReport(roster(), people);
    expect(report.inactiveButRegistered).toEqual([
      expect.objectContaining({ personId: 3, reason: 'dropped_out', expires: '2026-12-31', autoRenewOptedOut: true })
    ]);
  });

  it('Report_ListsActiveScoutsNotOnTheRoster', () => {
    const people = [person(9, 'New', 'Crossover', { scout: { active: true, inactiveReason: null } })];
    expect(buildRosterReport(roster(), people).notOnRoster).toEqual([
      expect.objectContaining({ personId: 9, kind: 'scout' })
    ]);
  });

  it('Report_ListsActiveAdultsWithARole_NotOnTheRoster', () => {
    const people = [person(8, 'Helpful', 'Parent', { leaderRoles: ['Merit Badge Counselor'] })];
    expect(buildRosterReport(roster(), people).notOnRoster).toEqual([
      expect.objectContaining({ personId: 8, kind: 'adult', detail: 'Merit Badge Counselor' })
    ]);
  });

  it('Report_IgnoresInactiveAdults_NotOnTheRoster', () => {
    const people = [person(8, 'Former', 'Leader', { active: false, leaderRoles: ['Committee Member'] })];
    expect(buildRosterReport(roster(), people).notOnRoster).toEqual([]);
  });

  it('Report_BuildsARegistrationUpdate_ForEachMatchedMember', () => {
    const people = [person(2, 'Robert', 'Leader', { bsaMemberId: '900002' })];
    expect(buildRosterReport(roster(), people).registrations).toEqual([
      {
        personId: 2,
        expires: '2026-12-31',
        status: 'Multiple',
        positions: ['Scoutmaster'],
        autoRenewOptedOut: false,
        asOf: '2026-10-20'
      }
    ]);
  });

  it('Report_NeverMatchesTwoMembers_ToOnePerson', () => {
    const twin = '"900004","","Anna","","Scout","","F","Youth Member","","","Scouts BSA","12","No","Never Taken","","","","","WI","","","","","","02/28/2027","New","Yes","","","No","",""';
    const report = buildRosterReport(parseBsaRosterCsv(csv(YOUTH_ANNA, twin)), [person(1, 'Anna', 'Scout')]);
    expect(report.unmatched.map((m) => m.memberId)).toEqual(['900001', '900004']);
  });
});
